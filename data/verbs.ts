function createVerb(infinitive: string, translation: string, _level: LanguageLevel): VerbData {
  void _level
  const exc = exceptions[infinitive]
  if (exc) {
    return {
      infinitive,
      firstPerson: exc.firstPerson,
      thirdPersonPlural: exc.thirdPersonPlural,
      pastMasculine: exc.pastMasculine,
      translation,
    }
  }
  const forms = regularForms(infinitive)
  return {
    infinitive,
    firstPerson: forms.firstPerson,
    thirdPersonPlural: forms.thirdPersonPlural,
    pastMasculine: forms.pastMasculine,
    translation,
  }
}

