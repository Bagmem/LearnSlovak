function regularForms(infinitive: string): { firstPerson: string; thirdPersonPlural: string; pastMasculine: string } {
  let stem = infinitive
  if (infinitive.endsWith("ť")) {
    stem = infinitive.slice(0, -2)
  }
  return {
    firstPerson: stem + "ím",
    thirdPersonPlural: stem + "ia",
    pastMasculine: stem + "l",
  }
}

